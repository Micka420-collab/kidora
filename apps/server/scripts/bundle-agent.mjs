// Bundle the Windows agent source into a TS module the server can embed in the
// pre-configured installer ZIP it streams to parents. Emitting a .ts (not JSON in
// src/generated, which is gitignored) means the bundle is committed AND refreshed
// on every build, so it's always present at runtime on any platform.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const agentDir = join(here, "..", "..", "agent-windows");
const outFile = join(here, "..", "src", "lib", "agent-bundle.generated.ts");

// The agent source may be absent (e.g. a server-only Docker build whose context
// is just apps/server). In that case keep the committed bundle instead of
// failing the build — it's checked in and refreshed on every full build.
if (!existsSync(agentDir)) {
  console.warn(`bundle-agent: agent source not found at ${agentDir} — keeping the committed bundle.`);
  process.exit(0);
}

// Source files a parent needs to run the agent (no runtime artifacts, no tests,
// no node_modules — the agent has zero npm deps).
const ROOT_FILES = [
  "agent.js",
  "package.json",
  "README.md",
  "sensor.ps1",
  "guardian.ps1",
  "overlay.ps1",
  "install-agent.ps1",
  "setup-windows.ps1",
  "Installer-Kidora.cmd",
];

function collect() {
  const files = {};
  for (const name of ROOT_FILES) {
    const p = join(agentDir, name);
    if (existsSync(p)) files[name] = readFileSync(p).toString("base64");
  }
  const libDir = join(agentDir, "lib");
  for (const f of readdirSync(libDir)) {
    if (f.endsWith(".js") && !f.endsWith(".test.js")) {
      files[`lib/${f}`] = readFileSync(join(libDir, f)).toString("base64");
    }
  }
  return files;
}

const files = collect();
const count = Object.keys(files).length;
let version = "1.0.0";
try {
  version = JSON.parse(readFileSync(join(agentDir, "package.json"), "utf8")).version || version;
} catch { /* keep default */ }
const body = `// AUTO-GENERATED by scripts/bundle-agent.mjs — do not edit by hand.
// Windows agent source, base64-encoded, for the pre-configured installer ZIP
// and self-update endpoint.
export const AGENT_BUNDLE: Record<string, string> = ${JSON.stringify(files, null, 0)};
export const AGENT_BUNDLE_FILE_COUNT = ${count};
export const AGENT_BUNDLE_VERSION = ${JSON.stringify(version)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, "utf8");
console.log(`bundle-agent: wrote ${count} files -> ${outFile}`);
